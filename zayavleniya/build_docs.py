def build_docx(path, addr_lines, title, paras, asks, apps, extra_from=None, apps_note=None):
    doc = setup_doc()
    add_right(doc, addr_lines)
    doc.add_paragraph()
    add_right(doc, extra_from or FROM_BLOCK)
    doc.add_paragraph()
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(4)
    r = p.add_run("ЗАЯВЛЕНИЕ")
    set_run_font(r, 14, True)
    p2 = doc.add_paragraph()
    p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p2.paragraph_format.space_after = Pt(10)
    r2 = p2.add_run(title)
    set_run_font(r2, 14, False)
    for t in paras:
        add_body(doc, t)
    add_body(doc, "На основании изложенного прошу:", first_line=True)
    for i, t in enumerate(asks, 1):
        add_body(doc, f"{i}. {t}", first_line=True)
    if apps_note:
        add_body(doc, apps_note, first_line=True)
    elif apps:
        add_body(doc, "Приложения:", first_line=True)
        for i, t in enumerate(apps, 1):
            add_body(doc, f"{i}) {t}", first_line=True)
    add_body(
        doc,
        "Дата: [дата]          Подпись _____________ / [ФИО] /",
        first_line=False,
        align="left",
    )
    add_body(
        doc,
        "Отметка канцелярии (заполняет принимающий): входящий № ________ от «___» ________ 20___ г. _____________",
        first_line=False,
        align="left",
    )
    doc.save(path)


